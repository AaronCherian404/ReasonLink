#!/usr/bin/env python3
"""Generate the P3 result figure data from the board summary.

Usage (from the P3 folder, full repository present):
    python3 figures/generate-p3-figures.py [--summary PATH]
Reads ../../results/p2/board/csv/board_summary.json (100-puzzle VCU118 runs,
2026-11-05) and writes figures/p3-results.tex (the TikZ figure)
plus figures/p3-macros.tex. Standard library only;
runs no experiments.
"""
import argparse, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT = os.path.join(HERE, '..', '..', '..', 'results', 'p2', 'board', 'csv', 'board_summary.json')

# (label, run key); bottom to top in the horizontal bar chart
SERIAL = [
    ('B1 replay$^\\ast$', 'board_serial_faithful_trace'),
    ('HW delta + B', 'board_serial_reasonlink_resident'),
    ('HW delta', 'board_serial_reasonlink'),
    ('B3 + B', 'board_serial_delta_resident'),
    ('B3 CPU delta', 'board_serial_delta'),
    ('B2 lean', 'board_serial_lean'),
    ('B1 faithful', 'board_serial_faithful'),
]
SHARE = [('B1', 'faithful'), ('B2', 'lean'), ('B3', 'delta'), ('HW', 'reasonlink')]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--summary', default=DEFAULT)
    s = json.load(open(ap.parse_args().summary))

    # (a) median per-puzzle stages in seconds: NVDLA, handoff (conv + xfer), solve
    rows = []
    for i, (label, key) in enumerate(SERIAL):
        m = s[key]['median_us']
        rows.append((i, label, m['T_nn'] / 1e6, (m['T_conv'] + m['T_xfer']) / 1e6, m['T_sat'] / 1e6,
                     100 * s[key]['handoff_share']))
    coords = lambda col: ' '.join('(%.4f,%d)' % (r[col], r[0]) for r in rows)
    shares = '\n'.join('\\node[anchor=west,font=\\tiny,inner sep=1pt] at (axis cs:%.4f,%d) {%s\\%%};' %
                       (r[2] + r[3] + r[4], r[0], ('%.1f' % r[5]) if r[5] >= 1 else ('%.2f' % r[5]))
                       for r in rows)
    labels = ','.join('{%s}' % r[1] for r in rows)

    # (b) handoff share, serial vs exposed (double-buffered); negative -> 0 (fully hidden)
    def share(mode):
        return ' '.join('(%s,%.2f)' % (lab, max(0.0, 100 * s['board_%s_%s' % (mode, k)]['handoff_share']))
                        for lab, k in SHARE)

    fig = r"""%% generated by generate-p3-figures.py from board_summary.json; do not edit
\begin{tikzpicture}
\begin{axis}[name=bd,width=0.60\textwidth,height=3.7cm,xbar stacked,bar width=6pt,
 xmin=0,xmax=4.4,ymin=-0.6,ymax=6.6,ytick={0,...,6},yticklabels={%s},
 xlabel={Seconds per puzzle (median stages)},title={(a) Serial: where the time goes},
 tick label style={font=\scriptsize},label style={font=\scriptsize},title style={font=\footnotesize},
 xmajorgrids,grid style={gray!20},
 legend style={font=\scriptsize,at={(0.99,0.03)},anchor=south east,legend columns=1,draw=gray!50}]
\addplot[fill=blue!45,draw=blue!60] coordinates {%s};
\addplot[fill=orange!80,draw=orange!90!black] coordinates {%s};
\addplot[fill=green!55!black,draw=green!40!black] coordinates {%s};
\legend{NVDLA $T_{nn}$,Handoff $T_{conv}{+}T_{xfer}$,Solve $T_{sat}$}
%s
\end{axis}
\begin{axis}[at={(bd.east)},anchor=west,xshift=1.1cm,width=0.40\textwidth,height=3.7cm,
 ybar,bar width=7pt,ymin=0,ymax=42,symbolic x coords={B1,B2,B3,HW},xtick=data,
 ylabel={Handoff share (\%%)},title={(b) Overlap (H2): serial vs.\ double},
 tick label style={font=\scriptsize},label style={font=\scriptsize},title style={font=\footnotesize},
 nodes near coords,nodes near coords style={font=\tiny},every node near coord/.append style={/pgf/number format/fixed,/pgf/number format/precision=1},
 ymajorgrids,grid style={gray!20},enlarge x limits=0.18,
 legend style={font=\scriptsize,at={(0.98,0.98)},anchor=north east,draw=gray!50}]
\addplot[fill=blue!45,draw=blue!60] coordinates {%s};
\addplot[fill=orange!80,draw=orange!90!black] coordinates {%s};
\legend{Serial,Double-buffered (exposed)}
\end{axis}
\end{tikzpicture}
""" % (labels, coords(2), coords(3), coords(4), shares, share('serial'), share('double'))
    with open(os.path.join(HERE, 'p3-results.tex'), 'w') as f:
        f.write(fig)

    def w(key):
        return s[key]['wall_us_per_puzzle_no_stalls'] / 1e6
    with open(os.path.join(HERE, 'p3-macros.tex'), 'w') as f:
        f.write('% generated by generate-p3-figures.py from board_summary.json; do not edit\n')
        for name, key in [('WallFaithful', 'board_serial_faithful'), ('WallLean', 'board_serial_lean'),
                          ('WallDelta', 'board_serial_delta'), ('WallDeltaB', 'board_serial_delta_resident'),
                          ('WallRL', 'board_serial_reasonlink'), ('WallRLB', 'board_serial_reasonlink_resident'),
                          ('WallReplay', 'board_serial_faithful_trace')]:
            f.write('\\newcommand{\\%s}{%.2f}\n' % (name, w(key)))
    print('wrote p3-results.tex, p3-macros.tex')
    for r in rows:
        print('  %-18s nn %.3f s  handoff %.4f s  sat %.4f s  share %.2f%%' % (r[1], r[2], r[3], r[4], r[5]))


if __name__ == '__main__':
    main()
