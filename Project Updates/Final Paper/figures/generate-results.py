#!/usr/bin/env python3
"""Regenerate final-paper result assets from the recorded board summary.

Uses only the Python standard library. Run from any directory. An optional
summary path permits regeneration from a separately archived result set.
This script does not rerun board experiments or re-estimate interference.
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path


def main():
    out = Path(__file__).resolve().parent
    repo = out.parents[2]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--summary", type=Path,
                        default=repo / "results/p2/board/csv/board_summary.json")
    args = parser.parse_args()
    raw = args.summary.read_bytes()
    summary = json.loads(raw)
    configurations = [
        ("faithful", "Faithful full image"),
        ("lean", "Lean full image"),
        ("delta", "CPU-generated delta"),
        ("delta_resident", "CPU-generated delta"),
        ("reasonlink", "Hardware-generated delta"),
        ("reasonlink_resident", "Hardware-generated delta"),
    ]
    for mode in ("serial", "double"):
        with (out / f"{mode}-walltime.tsv").open("w", newline="") as f:
            writer = csv.writer(f, delimiter="\t", lineterminator="\n")
            writer.writerow(["index", "measured_s", "adjusted_s"])
            for i, (key, _) in enumerate(configurations):
                s = summary[f"board_{mode}_{key}"]
                if s["check"]["wrong"] or not s["check"]["identical_across_runs"]:
                    raise ValueError(f"Failed correctness check: {mode}/{key}")
                writer.writerow([i, f'{s["wall_us_per_puzzle"] / 1e6:.6f}',
                                 f'{s["wall_us_per_puzzle_no_stalls"] / 1e6:.6f}'])
    rows = []
    for key, label in configurations:
        s = summary[f"board_serial_{key}"]
        m = s["median_us"]
        numbers = [f'{m[k] / 1000:.3f}' for k in
                   ("T_nn", "T_conv", "T_xfer", "T_sync", "T_sat")]
        rows.append(" & ".join([label, "Yes" if s["resident"] else "No", *numbers, f'{s["bytes_moved"]:,}']) + r" \\")
    (out / "serial-rows.tex").write_text("\n".join(rows) + "\n\\bottomrule\n")

    def serial(key):
        return summary[f"board_serial_{key}"]

    def adjusted(key):
        return serial(key)["wall_us_per_puzzle_no_stalls"] / 1e6

    delta_sat = serial("delta")["median_us"]["T_sat"] / 1000
    resident_sat = serial("delta_resident")["median_us"]["T_sat"] / 1000
    macros = {
        "SerialDeltaAdjusted": (adjusted("delta"), 3),
        "SerialRLAdjusted": (adjusted("reasonlink"), 3),
        "SerialDeltaResidentAdjusted": (adjusted("delta_resident"), 3),
        "SerialRLResidentAdjusted": (adjusted("reasonlink_resident"), 3),
        "DeltaRLDifference": (100 * abs(adjusted("delta") - adjusted("reasonlink"))
                              / adjusted("delta"), 2),
        "FaithfulRLSpeedup": (adjusted("faithful") / adjusted("reasonlink"), 2),
        "LeanRLSpeedup": (adjusted("lean") / adjusted("reasonlink"), 2),
        "DeltaSat": (delta_sat, 2),
        "DeltaResidentSat": (resident_sat, 2),
        "ResidentReduction": (100 * (1 - resident_sat / delta_sat), 1),
    }
    (out / "result-macros.tex").write_text(
        "% Generated by generate-results.py; do not edit by hand.\n" +
        "".join(f"\\newcommand{{\\{name}}}{{{value:.{digits}f}}}\n"
                for name, (value, digits) in macros.items()))
    (out / "source-provenance.json").write_text(json.dumps({
        "source": "results/p2/board/csv/board_summary.json",
        "source_sha256": hashlib.sha256(raw).hexdigest(),
        "configurations": len(summary),
        "puzzles_per_configuration": sorted({s["puzzles"] for s in summary.values()}),
        "wall_units": "seconds per puzzle; mean whole-run wall time",
        "stage_units": "milliseconds per puzzle; median stage intervals",
        "adjustment": "Existing summary estimate; not a clean repeated measurement",
    }, indent=2) + "\n")
    print(f"Generated result assets in {out}")


if __name__ == "__main__":
    main()
