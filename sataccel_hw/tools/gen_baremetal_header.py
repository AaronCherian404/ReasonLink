"""Turn a tb_tool test directory into a C header for the ESP bare-metal test.

The bare-metal app (esp_soc/apps/baremetal/sataccel) replays the driver
core's recorded register program (ops.txt), after copying the recorded
device memory (mem.txt) to the same physical addresses, and checks the
result against the instance (inst.cnf, meta.txt). Generate the test dir with
TB_MEM=used so mem.txt holds every word of the image's used ranges.

Usage: python3 gen_baremetal_header.py <test_dir> <out.h>
"""
import sys
from pathlib import Path


def main():
    d, out = Path(sys.argv[1]), Path(sys.argv[2])
    ops = []
    readback = []
    for line in (d / "ops.txt").read_text().splitlines():
        f = line.split()
        if not f or f[0].startswith("#"):
            continue
        if f[0] == "W":
            ops.append((0, int(f[1], 16), int(f[2], 16), 0))
        elif f[0] == "P":
            ops.append((1, int(f[1], 16), int(f[2], 16), int(f[3], 16)))
        elif f[0] == "C":
            ops.append((2, 0, 0, 0))
        elif f[0] == "D":
            readback.append((int(f[1], 16), int(f[2], 16)))

    # memory: contiguous runs of 8-byte words
    words = []
    for line in (d / "mem.txt").read_text().splitlines():
        a, v = line.split()
        words.append((int(a, 16), int(v, 16)))
    words.sort()
    runs, data = [], []
    for a, v in words:
        if runs and runs[-1][0] + 8 * runs[-1][1] == a:
            runs[-1][1] += 1
        else:
            runs.append([a, 1])
        data.append(v)

    meta = (d / "meta.txt").read_text().split()
    num_vars, expect = int(meta[0]), int(meta[1])
    clauses = []
    for line in (d / "inst.cnf").read_text().splitlines():
        if line.startswith(("p", "c")) or not line.strip():
            continue
        lits = [int(x) for x in line.split()]
        clauses.append(lits[:-1])

    o = ["/* Generated by sataccel_hw/tools/gen_baremetal_header.py from %s */" % d.name,
         "#ifndef SATACCEL_TEST_H", "#define SATACCEL_TEST_H", "#include <stdint.h>", "",
         '#define SA_TEST_NAME "%s"' % d.name,
         "#define SA_TEST_NUM_VARS %d" % num_vars,
         "#define SA_TEST_EXPECT %d   /* 1 SAT, 0 UNSAT */" % expect,
         "#define SA_TEST_ANSWER_ADDR 0x%08xu" % readback[0][0],
         "#define SA_TEST_MISC_ADDR 0x%08xu" % readback[1][0], "",
         "/* register program: {op (0 write, 1 poll, 2 counters), offset, value/mask, poll value} */",
         "static const uint32_t sa_test_ops[][4] = {"]
    o += ["    {%d, 0x%05x, 0x%08x, 0x%08x}," % op for op in ops]
    o += ["};", "", "/* device memory: runs of 64-bit words {address, count} */",
          "static const uint32_t sa_test_runs[][2] = {"]
    o += ["    {0x%08x, %d}," % (a, n) for a, n in runs]
    o += ["};", "static const uint64_t sa_test_data[] = {"]
    for i in range(0, len(data), 4):
        o.append("    " + " ".join("0x%016xull," % v for v in data[i:i + 4]))
    o += ["};", "", "/* the instance, for checking the model: literals, 0-terminated clauses */",
          "static const int32_t sa_test_cnf[] = {"]
    for c in clauses:
        o.append("    " + " ".join(str(x) + "," for x in c) + " 0,")
    o += ["};", "#define SA_TEST_NUM_CLAUSES %d" % len(clauses), "", "#endif", ""]
    out.write_text("\n".join(o))
    print(f"{out}: {len(ops)} ops, {len(runs)} runs / {len(data)} words, {len(clauses)} clauses")


if __name__ == "__main__":
    main()
